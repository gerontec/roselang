#!/usr/bin/env python3
"""Browsable overview of the drug cards (bio:drug.*) for GitHub, grouped by ATC: docs/pharma/README.md
(index by anatomical main group) and one page per main group, sub-grouped by the second level.
Group names are Wikidata's own labels (CC0) where Wikidata has one, else only the code - the WHO
ATC index is not used (its terms forbid commercial distribution and changes).
Source: rose/std/catalog.jsonl.gz. Usage: pharma_overview.py [--out docs/pharma]"""
import argparse
import collections
import json
import os
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=os.path.join(ROOT, "docs", "pharma"))
    a = ap.parse_args()
    import gzip
    cards = [json.loads(l) for l in gzip.open(os.path.join(ROOT, "rose", "std", "catalog.jsonl.gz"), "rt", encoding="utf-8")]
    drugs = [c for c in cards if c["ref"].startswith("bio:drug.")]
    names = {}                                            # group code -> Wikidata label, from the cards themselves
    for c in drugs:
        for g in c.get("atc_groups") or []:
            code, _, lab = g.partition(" ")
            names[code] = lab
    by1 = collections.defaultdict(lambda: collections.defaultdict(list))
    for c in drugs:
        codes = c.get("atc") or []
        if not codes:
            by1["-"]["-"].append((c, None))
        for code in sorted(set(codes)):
            by1[code[0]][code[:3]].append((c, code))
    os.makedirs(a.out, exist_ok=True)
    for f in os.listdir(a.out):
        if f.endswith(".md"):
            os.remove(os.path.join(a.out, f))

    def title(code):
        return code + (f" {names[code]}" if code in names else "") if code != "-" else "no ATC code"

    def line(c, code):
        found = "found in organisms" if "found in organisms" in c["intent"] else ""
        before = "US approval before 1982" if "before 1982" in c["intent"] else ""
        tags = ", ".join(x for x in (found, before) if x)
        return f"- **{c['name']}**" + (f" `{code}`" if code else "") + (f" – {tags}" if tags else "") + \
            f" · `{c['ref']}` · [source]({c['url']})"

    index = []
    for top in sorted(by1):
        fn = ("atc-" + top.lower() if top != "-" else "no-atc") + ".md"
        n = len({c["ref"] for subs in by1[top].values() for c, _ in subs})
        index.append(f"- [{title(top)}]({fn}) ({n})")
        with open(os.path.join(a.out, fn), "w", encoding="utf-8") as f:
            f.write(f"# {title(top)}\n\n[Index](README.md) · {n} drugs, by ATC group\n\n")
            for sub in sorted(by1[top]):
                rows = sorted(by1[top][sub], key=lambda x: (x[1] or "", x[0]["name"].lower()))
                f.write(f"## {title(sub)}\n\n" + "\n".join(line(c, code) for c, code in rows) + "\n\n")
    n_nat = sum(1 for c in drugs if "found in organisms" in c["intent"])
    n_old = sum(1 for c in drugs if "before 1982" in c["intent"])
    with open(os.path.join(a.out, "README.md"), "w", encoding="utf-8") as f:
        f.write("# Drugs in Rose, by ATC group\n\n"
                f"{len(drugs)} drug cards (`bio:drug.*`): {n_nat} recorded in Wikidata as found in organisms "
                "(plants, fungi, bacteria; mostly from LOTUS, with the publication behind each claim), and drugs "
                f"known before ivermectin – US approval before 1982 in the FDA Orange Book ({n_old} cards carry "
                "this note). Pointers only: no dose, preparation or safety information – see each drug's own "
                "documentation.\n\n"
                "- ATC codes from Wikidata (CC0); group names are Wikidata's own labels where Wikidata has one, "
                "otherwise only the code is shown (the WHO ATC index is not reproduced: its terms do not allow "
                "commercial distribution or changes)\n"
                "- a drug with several ATC codes is listed under each of them\n"
                "- generated by `tools/pharma_overview.py` from `rose/std/catalog.jsonl.gz`; background in "
                "[docs/CONCEPT.md §5.8](../CONCEPT.md)\n\n## Anatomical main groups\n\n" + "\n".join(index) + "\n")
    print(f"{len(drugs)} drugs, {len(index)} pages, {len(names)} group names")


if __name__ == "__main__":
    sys.exit(main())
