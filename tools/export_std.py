#!/usr/bin/env python3
"""Generate the standard library std/ from the corpus: knowledge as Rose source.

Only CC0 / public-domain sources (Wikidata, CODATA) - share-alike data (OEIS) stays in the corpus.
  std/law.rose         laws with verified Rose source (level parsed/tested), physics
  std/math.rose        mathematical formulas with Rose source
  std/const/codata.rose  CODATA constants
  std/open.rose        open problems as `open` declarations (negative knowledge)
  std/index.json       ref -> {file, name, kind, level, license, url}
  std/catalog.jsonl    one card per unit of every non-share-alike source (also cards without Rose
                       source): the compiler's built-in knowledge for `rosec plan/search/get`
  std/catalog.vec      optional: int8 bge-m3 vectors in catalog order (--vectors, not in git)
Usage: export_std.py [--out ../rose/std] [--vectors]
"""
import argparse
import json
import os
import re
import sys

import rose_db as R

HEADER = "# generated by tools/export_std.py from the Rose corpus - do not edit\n# source: {src}, licence: {lic}\n"


def law_item_name(src):
    m = re.match(r"\s*law\s+([A-Za-z_][A-Za-z0-9_]*)", src)
    return m.group(1) if m else None


def const_item_name(src):
    m = re.match(r"\s*const\s+([A-Za-z_][A-Za-z0-9_]*)", src)
    return m.group(1) if m else None


def ident(ref):
    n = re.sub(r"[^A-Za-z0-9_]", "_", ref.split(":", 1)[1])
    return ("p_" + n) if n[0].isdigit() else n


def qstr(s):
    return '"' + (s or "").replace('"', "'").replace("\n", " ")[:400] + '"'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "rose", "std"))
    ap.add_argument("--vectors", action="store_true")
    a = ap.parse_args()
    out = os.path.abspath(a.out)
    os.makedirs(os.path.join(out, "const"), exist_ok=True)
    con = R.connect()
    cur = con.cursor()
    index, files = {}, {"law.rose": [], "math.rose": [], "const/codata.rose": [], "open.rose": []}

    cur.execute("SELECT u.ref, u.kind, u.rose_src, u.level, u.source_url, s.license FROM rose_unit u "
                "JOIN rose_source s USING (source_id) WHERE s.name='wikidata' AND u.rose_src IS NOT NULL "
                "AND u.kind IN ('law','math','const','bio') AND u.level IN ('parsed','tested','cross_checked','proven') "
                "ORDER BY u.ref")
    for ref, kind, src, level, url, lic in cur.fetchall():
        f = "law.rose" if kind == "law" else "math.rose"
        name = law_item_name(src)
        if not name:
            continue
        files[f].append(src.rstrip() + "\n")
        index[ref] = {"file": f, "name": name, "kind": kind, "level": level, "license": lic, "url": url}

    cur.execute("SELECT u.ref, u.rose_src, u.level, u.source_url, s.license FROM rose_unit u "
                "JOIN rose_source s USING (source_id) WHERE s.name='codata' AND u.rose_src IS NOT NULL ORDER BY u.ref")
    for ref, src, level, url, lic in cur.fetchall():
        name = const_item_name(src)
        files["const/codata.rose"].append(src.rstrip())
        index[ref] = {"file": "const/codata.rose", "name": name, "kind": "const", "level": level,
                      "license": lic, "url": url}

    cur.execute("SELECT u.ref, u.name, u.intent, u.source_url, s.license, JSON_VALUE(u.payload,'$.wikidata') "
                "FROM rose_unit u JOIN rose_source s USING (source_id) WHERE u.kind='open' ORDER BY u.ref")
    for ref, name, intent, url, lic, q in cur.fetchall():
        n = ident(ref)
        files["open.rose"].append(f"open {n}\n  intent {qstr(intent)}\n" + (f"  ref wikidata:{q}\n" if q else "") + "end\n")
        index[ref] = {"file": "open.rose", "name": n, "kind": "open", "level": "imported", "license": lic, "url": url}

    meta = {"law.rose": ("std.law", "Wikidata", "CC0-1.0"), "math.rose": ("std.math", "Wikidata", "CC0-1.0"),
            "const/codata.rose": ("std.const.codata", "CODATA (NIST)", "public domain"),
            "open.rose": ("std.open", "Wikidata", "CC0-1.0")}
    for f, items in files.items():
        mod, src, lic = meta[f]
        sep = "\n" if f.startswith("const") else "\n\n"
        with open(os.path.join(out, f), "w", encoding="utf-8") as fh:
            fh.write(HEADER.format(src=src, lic=lic) + f"module {mod}\n\n" + sep.join(items) + "\n")
    with open(os.path.join(out, "index.json"), "w", encoding="utf-8") as fh:
        json.dump(index, fh, indent=0, sort_keys=True, ensure_ascii=False)
    print({f: len(v) for f, v in files.items()}, "index:", len(index))
    export_catalog(cur, out, index, a.vectors)


OWN_SETS = ("mathlib", "rosettacode")   # exported as built-in sets by export_pack.py, not into catalog.jsonl


def export_catalog(cur, out, index, vectors):
    cur.execute("SELECT scheme, value, unit_id FROM rose_alias")
    aliases = {}
    for scheme, value, uid in cur.fetchall():
        aliases.setdefault(uid, []).append(f"{scheme}:{value}")
    cur.execute("SELECT u.unit_id, u.ref, u.kind, u.name, u.intent, u.signature, u.level, u.payload, u.source_url, "
                "s.name, s.license FROM rose_unit u JOIN rose_source s USING (source_id) "
                "WHERE s.share_alike=0 AND s.name NOT IN (" + ",".join(f"'{x}'" for x in OWN_SETS) + ") "
                "ORDER BY u.ref")
    ids = []
    with open(os.path.join(out, "catalog.jsonl"), "w", encoding="utf-8") as fh:
        for uid, ref, kind, name, intent, sig, level, payload, url, src, lic in cur.fetchall():
            p = json.loads(payload) if payload else {}
            card = {"ref": ref, "kind": kind, "name": name, "intent": intent, "level": level, "source": src,
                    "license": lic, "url": url, "std": ref in index}
            for k in ("domain", "status", "proved_year", "complexity"):
                if p.get(k):
                    card[k] = p[k]
            if p.get("proved_by"):
                card["proved_by"] = [x.get("label") for x in p["proved_by"]]
            if sig:
                card["signature"] = sig
            if p.get("tex"):
                card["tex"] = p["tex"][0]
            if uid in aliases:
                card["aliases"] = sorted(aliases[uid])
            fh.write(json.dumps(card, ensure_ascii=False, sort_keys=True) + "\n")
            ids.append(uid)
    print("catalog:", len(ids))
    if not vectors:
        return
    import numpy as np
    m = np.zeros((len(ids), 1024), dtype=np.int8)
    pos = {uid: i for i, uid in enumerate(ids)}
    cur.execute("SELECT unit_id, VEC_ToText(v) FROM rose_embedding WHERE unit_id IN "
                "(SELECT unit_id FROM rose_unit u JOIN rose_source s USING (source_id) WHERE s.share_alike=0 "
                "AND s.name NOT IN (" + ",".join(f"'{x}'" for x in OWN_SETS) + "))")
    n = 0
    for uid, txt in cur.fetchall():
        v = np.array(json.loads(txt), dtype=np.float32)
        v /= np.linalg.norm(v) or 1.0
        m[pos[uid]] = np.round(v * 127).astype(np.int8)
        n += 1
    m.tofile(os.path.join(out, "catalog.vec"))
    print("vectors:", n)


if __name__ == "__main__":
    sys.exit(main())
