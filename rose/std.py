"""The generated standard library std/: corpus knowledge as Rose source.

std/index.json maps a ref (law:..., const:codata..., open:...) to a file and an item name.
Files are generated by tools/export_std.py from CC0 / public-domain sources only.
"""
import json
import os

from .nodes import Const, Law, Open
from .parser import parse

STD = os.path.join(os.path.dirname(os.path.abspath(__file__)), "std")
_index = None
_files = {}


def index():
    global _index
    if _index is None:
        try:
            with open(os.path.join(STD, "index.json"), encoding="utf-8") as f:
                _index = json.load(f)
        except FileNotFoundError:
            _index = {}
    return _index


def _items(file):
    if file not in _files:
        with open(os.path.join(STD, file), encoding="utf-8") as f:
            mod = parse(f.read(), "std/" + file)
        _files[file] = {it.name: it for it in mod.items if isinstance(it, (Law, Const, Open))}
    return _files[file]


def lookup(ref):
    meta = index().get(ref)
    if meta is None:
        return None
    item = _items(meta["file"]).get(meta["name"])
    return (item, meta) if item is not None else None
